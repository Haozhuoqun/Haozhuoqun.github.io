// 线性插值函数：在给定波长获取 n 和 k
function getOpticalConstants(metalKey, wavelength) {
  const metal = METALS_DATA[metalKey];
  if (!metal) return null;

  const wls = metal.wavelengths;
  const nArr = metal.n;
  const kArr = metal.k;

  // 边界处理
  if (wavelength <= wls[0]) return { n: nArr[0], k: kArr[0] };
  if (wavelength >= wls[wls.length - 1]) return { n: nArr[wls.length - 1], k: kArr[wls.length - 1] };

  // 线性插值
  let i = 0;
  while (i < wls.length - 1 && wls[i + 1] < wavelength) i++;

  const t = (wavelength - wls[i]) / (wls[i + 1] - wls[i]);
  return {
    n: nArr[i] + t * (nArr[i + 1] - nArr[i]),
    k: kArr[i] + t * (kArr[i + 1] - kArr[i])
  };
}

